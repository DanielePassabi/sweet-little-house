import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.js';
import {createTerraceDoor,terraceDoorLayout as d,terraceMovingStart} from '../dist/terrace-door.js';
import {freezeStaticTransforms} from '../dist/render-state.js';
import {canWalk,setDoorCollisionTest} from '../dist/furniture-collisions.js';

const scene=new THREE.Scene(),events=[],system=createTerraceDoor(scene,{onStateChange:s=>events.push(s)});
freezeStaticTransforms(scene);setDoorCollisionTest(system.blocksPoint);
const world=(u,v=0)=>({x:d.x+d.ux*u-d.uz*v,z:d.z+d.uz*u+d.ux*v});
const step=(occupants=[])=>{for(let i=0;i<90;i++)system.update(1/60,occupants);};
const p=world(d.width*.77),fixed=world(d.width*.25),ray=new THREE.Raycaster();
assert.equal(canWalk(p.x,p.z),false,'Closed slider blocks terrace access');
assert.equal(system.group.getObjectByName('outer-jamb').material.color.getHexString(),'f7f6f2');
ray.set(new THREE.Vector3(p.x+d.uz*.5,1.4,p.z-d.ux*.5),new THREE.Vector3(-d.uz,0,d.ux));
assert.equal(system.pick(ray)?.id,'terrace');
const before=system.movingLeaf.matrixWorld.clone();system.toggle('terrace');step();
assert.equal(system.state[0].open,true);assert.notDeepEqual(system.movingLeaf.matrixWorld.elements,before.elements);
assert.ok(canWalk(p.x,p.z),'Open slider frees the passage');assert.ok(!canWalk(fixed.x,fixed.z),'Fixed pane remains solid');
assert.ok(Math.abs(system.movingLeaf.position.x-d.jamb)<1e-10,'Leaves overlap on separate tracks');
assert.ok(2*d.track>d.thickness,'Sliding leaves do not intersect');
assert.ok(d.width-d.jamb-(d.jamb+d.leafWidth)>.9,'Usable clear passage');
const open=world(d.jamb+d.leafWidth/2,-d.track);
ray.set(new THREE.Vector3(open.x+d.uz*.5,1.4,open.z-d.ux*.5),new THREE.Vector3(-d.uz,0,d.ux));
assert.equal(system.pick(ray)?.id,'terrace','Overlapped leaves remain clickable');
const blocker=new THREE.Mesh(new THREE.BoxGeometry(.2,.2,.2),new THREE.MeshBasicMaterial());blocker.position.copy(ray.ray.origin).addScaledVector(ray.ray.direction,.25);blocker.updateMatrixWorld();
assert.equal(system.pick(ray,[blocker]),null);
system.setOpen('terrace',false);step([{...p,r:.20}]);step([{...p,r:.20}]);assert.equal(system.state[0].open,true);assert.ok(events.some(s=>s.obstructed));
system.setOpen('terrace',false);system.update(.1);const partial=system.state[0].progress;
assert.equal(system.movingLeaf.position.x,terraceMovingStart(partial));system.toggle('terrace');assert.equal(system.state[0].progress,partial);step();
system.setOpen('terrace',false);step();assert.equal(system.state[0].progress,0);
assert.equal(system.update(.1),false);assert.equal(system.update(NaN),false);assert.throws(()=>system.toggle('missing'),RangeError);
setDoorCollisionTest(null);
console.log('PASS: white terrace slider, separate tracks, live walking collisions, clicks from open/closed positions, swept closing safety, reversal and idle rendering.');
